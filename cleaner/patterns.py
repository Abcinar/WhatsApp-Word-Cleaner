from __future__ import annotations

import re

# ---------------------------------------------------------
# WhatsApp Date / Time Patterns
# ---------------------------------------------------------

DATE_PATTERN = re.compile(
    r"""
    \[?
    \d{1,2}
    [./-]
    \d{1,2}
    [./-]
    \d{2,4}
    (?:\s+|,)
    \d{1,2}
    :
    \d{2}
    (?:
        :
        \d{2}
    )?
    \]?
    """,
    re.VERBOSE,
)

# ---------------------------------------------------------
# WhatsApp Export Header
#
# [12.05.2024 18:30] Ali:
# 12.05.2024, 18:30 - Ali:
# ---------------------------------------------------------

WHATSAPP_HEADER_PATTERN = re.compile(
    r"""
    ^
    \[?
    \d{1,2}[./-]\d{1,2}[./-]\d{2,4}
    (?:\s+|,)
    \d{1,2}:\d{2}
    (?::\d{2})?
    \]?
    \s*
    [-]?
    .*?:
    """,
    re.VERBOSE,
)

# ---------------------------------------------------------
# Standalone Line Numbers
#
# 3071
# 145
# ---------------------------------------------------------

LINE_NUMBER_PATTERN = re.compile(
    r"^\d{1,6}$"
)

# ---------------------------------------------------------
# Multiple Spaces
# ---------------------------------------------------------

MULTIPLE_SPACE_PATTERN = re.compile(
    r"[ \t]{2,}"
)

# ---------------------------------------------------------
# Multiple Blank Lines
# ---------------------------------------------------------

MULTIPLE_BLANK_LINES_PATTERN = re.compile(
    r"\n{3,}"
)

# ---------------------------------------------------------
# Phone Numbers
# ---------------------------------------------------------

PHONE_PATTERN = re.compile(
    r"""
    \+?
    \d[\d\s()-]{7,}\d
    """,
    re.VERBOSE,
)

# ---------------------------------------------------------
# Invisible Unicode Characters
# ---------------------------------------------------------

ZERO_WIDTH_PATTERN = re.compile(
    "[\u200B-\u200D\uFEFF]"
)
